#!/usr/bin/env node
/* Builds the Explorer's offline map: web/js/content/lazy/explorer/basemap.js
   Source data: Natural Earth 1:50m (public domain, naturalearthdata.com) as packaged in the sane-topojson npm package (MIT):
   land, lakes, countries, and the states and provinces of the United States and Canada. Mexico is drawn as a country.
   Projection: conic equal-area, standard parallels 20 N and 60 N, centered on 100 W (the usual shape of North America).
   The map is projected HERE into SVG paths, so the app needs no map library and no internet. The app projects each
   destination with the same formula (H.EXPLORER.project in hfq_explorer.js); this script prints test points that
   qa/hfq_r7_explorer.js checks against the app.
   Run: cd tools && npm install && node build_basemap.js */
const fs=require('fs'), path=require('path');
const req=m=>{ try{ return require(m); }catch(e){ return require(path.join(process.env.HTFA_VENDOR||'',m)); } };
const d3=req('d3-geo'), topo=req('topojson-client');
const SRC=require.resolve('sane-topojson/dist/north-america_50m.json',{paths:[__dirname,process.env.HTFA_VENDOR||__dirname]});
const simp=req('topojson-simplify');
let T=JSON.parse(fs.readFileSync(SRC,'utf8'));
// simplify for a phone-sized map: drop points whose triangle is under 0.006 square degrees (well under a pixel), then islands under 0.02 square degrees
T=simp.presimplify(T); T=simp.simplify(T,0.006); T=simp.filter(T,simp.filterWeight(T,0.02));
const W=1000, Hh=820, PAR=[20,60], ROT=[100,0];
const countries=topo.feature(T,T.objects.countries).features;
const focus=countries.filter(f=>['USA','CAN','MEX'].includes(f.id));
const proj=d3.geoConicEqualArea().parallels(PAR).rotate(ROT).center([0,0]);   // d3's default center is 33.6442 N: set it to 0 so the app's formula (and the record below) is the whole story
// fit to the box that holds the United States (with Alaska and Hawaii), Canada below the high Arctic, and Mexico:
// 168 W to 52 W, 15 N to 71 N. Its edges are sampled every degree because parallels curve in a conic projection.
const box=[]; for(let lo=-168;lo<=-52;lo++){ box.push([lo,15],[lo,71]); } for(let la=15;la<=71;la++){ box.push([-168,la],[-52,la]); }
proj.fitExtent([[14,14],[W-14,Hh-14]],{type:'MultiPoint',coordinates:box});
proj.clipExtent([[0,0],[W,Hh]]);
const gp=d3.geoPath(proj);
const round=d=>d?d.replace(/-?\d+\.\d+/g,n=>(Math.round(+n*10)/10).toString()):'';
const land=round(gp(topo.feature(T,T.objects.land)));
const lakes=round(gp({type:'FeatureCollection',features:topo.feature(T,T.objects.lakes).features.filter(f=>d3.geoArea(f)>4e-6)}));
const ctry=countries.map(f=>({id:f.id||'',na:['USA','CAN','MEX'].includes(f.id),d:round(gp(f))})).filter(c=>c.d);
const sub=round(gp(topo.mesh(T,T.objects.subunits,(a,b)=>a!==b)));
const k=proj.scale(), t=proj.translate();
const tests=[[38.88833,-77.02],[47.518,-122.297],[21.36,-157.9617],[19.7427,-98.9869],[48.952423,-54.622791]].map(([la,lo])=>{ const p=proj([lo,la]); return [la,lo,Math.round(p[0]*100)/100,Math.round(p[1]*100)/100]; });
const data={w:W,h:Hh,proj:{type:'conicEqualArea',parallels:PAR,rotate:ROT,center:proj.center(),scale:k,translate:t},tests,land,lakes,countries:ctry,subunits:sub,
 attribution:'Map data: Natural Earth (public domain), via sane-topojson. Projection: conic equal-area 20N/60N, 100W.'};
const out=path.join(__dirname,'..','web','js','content','lazy','explorer','basemap.js');
fs.mkdirSync(path.dirname(out),{recursive:true});
fs.writeFileSync(out,'/*! HypeTeen Flight Academy. Copyright (c) 2026 Hype Learning Academies. All rights reserved. Proprietary: no license granted; see LICENSE. */\n/* GENERATED by tools/build_basemap.js from Natural Earth 1:50m (public domain). Do not edit by hand. */\n(function(){ G.HFQ.addBasemap('+JSON.stringify(data)+'); })();\n');
console.log('basemap: '+Math.round(fs.statSync(out).size/1024)+' KB, scale '+k.toFixed(2)+', translate '+t.map(x=>x.toFixed(2)).join(','));
console.log('test points',JSON.stringify(tests));
